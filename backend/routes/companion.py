@router.get("")
async def get_companion(user: dict = Depends(get_current_user)):
    """Return the user's current Companion selection (if any) along with the
    most recently cached whisper so the frontend bubble can show it
    immediately without a second round-trip."""
    user_doc = await db.users.find_one({"user_id": user["user_id"]}) or {}
    companion = user_doc.get("companion_guide") or None
    if not companion:
        return {"companion": None, "whisper": None, "whisper_at": None}

    whisper = user_doc.get("companion_whisper") or _fallback_whisper(companion)
    whisper_at = user_doc.get("companion_whisper_at")
    return {
        "companion": companion,
        "whisper": whisper,
        "whisper_at": whisper_at.isoformat() if isinstance(whisper_at, datetime) else None,
    }


@router.put("")
async def set_companion(body: SelectCompanionBody, user: dict = Depends(get_current_user)):
    """Pick a guide as your Companion. PREMIUM-ONLY (Companion bubble is a
    premium feature regardless of which guide you choose)."""
    user_doc = await db.users.find_one({"user_id": user["user_id"]}) or {}
    if not user_doc.get("is_premium"):
        raise HTTPException(
            status_code=403,
            detail="Companion Guide is a premium feature. Upgrade to keep your guide with you always.",
        )

    guide_name = (body.guide_name or "").strip()
    if not guide_name:
        raise HTTPException(status_code=400, detail="guide_name is required")

    # Verify the user can actually use this guide (handles edge cases like a
    # free-on-promo Custom Guide selection)
    allowed, reason = await _user_can_use(user_doc, guide_name)
    if not allowed:
        raise HTTPException(status_code=403, detail=reason or "Guide unavailable.")

    # Seed an initial whisper so the bubble lights up immediately on return
    name_hint = user_doc.get("display_name") or user_doc.get("name")
    whisper = await _generate_whisper(guide_name, name_hint)

    await db.users.update_one(
        {"user_id": user["user_id"]},
        {
            "$set": {
                "companion_guide": guide_name,
                "companion_whisper": whisper,
                "companion_whisper_at": datetime.now(timezone.utc),
            }
        },
    )
    return {"companion": guide_name, "whisper": whisper}


@router.delete("")
async def clear_companion(user: dict = Depends(get_current_user)):
    """Remove the Companion selection."""
    await db.users.update_one(
        {"user_id": user["user_id"]},
        {
            "$unset": {
                "companion_guide": "",
                "companion_whisper": "",
                "companion_whisper_at": "",
            }
        },
    )
    return {"success": True}


@router.get("/whisper")
async def get_whisper(user: dict = Depends(get_current_user)):
    """Return one whisper from the user's Companion. Cached for ~1h to keep
    LLM costs minimal — set `?force=1` to regenerate."""
    user_doc = await db.users.find_one({"user_id": user["user_id"]}) or {}
    companion = user_doc.get("companion_guide")
    if not companion:
        raise HTTPException(status_code=404, detail="No Companion selected")

    cached = user_doc.get("companion_whisper")
    cached_at = user_doc.get("companion_whisper_at")
    now = datetime.now(timezone.utc)

    # MongoDB returns datetimes as naive (BSON Date strips tzinfo); normalize
    # to UTC-aware before doing arithmetic with `now`.
    if isinstance(cached_at, datetime) and cached_at.tzinfo is None:
        cached_at = cached_at.replace(tzinfo=timezone.utc)

    if (
        cached
        and isinstance(cached_at, datetime)
        and (now - cached_at).total_seconds() < WHISPER_CACHE_TTL_SECONDS
    ):
        return {"whisper": cached, "cached": True, "guide": companion}

    name_hint = user_doc.get("display_name") or user_doc.get("name")
    whisper = await _generate_whisper(companion, name_hint)
    await db.users.update_one(
        {"user_id": user["user_id"]},
        {
            "$set": {
                "companion_whisper": whisper,
                "companion_whisper_at": now,
            }
        },
    )
    return {"whisper": whisper, "cached": False, "guide": companion}


@router.get("/whispers/today")
async def get_todays_whispers(user: dict = Depends(get_current_user)):
    """Return 3 whispers for today's scheduled local notifications.

    The frontend schedules these via expo-notifications' local notification
    API (no FCM/APNs needed) at three user-customizable times: morning,
    afternoon, evening."""
    user_doc = await db.users.find_one({"user_id": user["user_id"]}) or {}
    companion = user_doc.get("companion_guide")
    if not companion:
        raise HTTPException(status_code=404, detail="No Companion selected")

    name_hint = user_doc.get("display_name") or user_doc.get("name")
    # Generate the 3 whispers in parallel — cuts latency ~3x.
    import asyncio
    whispers: List[str] = await asyncio.gather(
        *[_generate_whisper(companion, name_hint) for _ in range(DAILY_WHISPER_COUNT)]
    )

    return {
        "guide": companion,
        "whispers": whispers,
        "generated_at": datetime.now(timezone.utc).isoformat(),
    }
